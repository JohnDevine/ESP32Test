/**
 * @brief Append a string to a fixed-size buffer without overflowing it.
 *
 * @param[in,out] dst      Destination buffer.
 * @param[in]     dst_size Total size of @p dst.
 * @param[in]     src      String to append.
 */
static void append_str(char *dst, size_t dst_size, const char *src)
{
    size_t len = strlen(dst);
    if (len < dst_size - 1) {
        strncat(dst, src, dst_size - 1 - len);
    }
}

/**
 * @brief Build the space-separated list of PHY modes advertised by an AP.
 *
 * @param[in]  ap       Access point record.
 * @param[out] dst      Destination buffer.
 * @param[in]  dst_size Total size of @p dst.
 */
static void phy_modes_to_str(const wifi_ap_record_t *ap, char *dst, size_t dst_size)
{
    dst[0] = '\0';

    if (ap->phy_11b) {
        append_str(dst, dst_size, "11b ");
    }
    if (ap->phy_11g) {
        append_str(dst, dst_size, "11g ");
    }
    if (ap->phy_11n) {
        append_str(dst, dst_size, "11n ");
    }
    if (ap->phy_lr) {
        append_str(dst, dst_size, "LR ");
    }
    if (ap->phy_11a) {
        append_str(dst, dst_size, "11a ");
    }
    if (ap->phy_11ac) {
        append_str(dst, dst_size, "11ac ");
    }
    if (ap->phy_11ax) {
        append_str(dst, dst_size, "11ax ");
    }
}

/**
 * @brief Escape a string for safe inclusion in a JSON string literal.
 *
 * @param[out] dst      Destination buffer.
 * @param[in]  dst_size Total size of @p dst.
 * @param[in]  src      Source string.
 */
static void json_escape(char *dst, size_t dst_size, const char *src)
{
    size_t j = 0;

    for (size_t i = 0; src[i] != '\0' && j + 1 < dst_size; i++) {
        unsigned char c = (unsigned char)src[i];

        if (c == '"' || c == '\\') {
            if (j + 2 >= dst_size) {
                break;
            }
            dst[j++] = '\\';
            dst[j++] = (char)c;
        } else if (c < 0x20) {
            if (j + 6 >= dst_size) {
                break;
            }
            snprintf(dst + j, dst_size - j, "\\u%04x", c);
            j += 6;
        } else {
            dst[j++] = (char)c;
        }
    }
    dst[j] = '\0';
}

/**
 * @brief Append formatted text to a buffer while tracking the write offset.
 *
 * @param[in,out] buf      Destination buffer.
 * @param[in]     size     Total size of @p buf.
 * @param[in,out] off      Current write offset.
 * @param[in]     fmt      printf-style format string.
 * @param[in]     ...      Format arguments.
 */
static void appendf(char *buf, size_t size, size_t *off, const char *fmt, ...)
{
    if (*off >= size) {
        return;
    }

    va_list args;
    va_start(args, fmt);
    int written = vsnprintf(buf + *off, size - *off, fmt, args);
    va_end(args);

    if (written > 0) {
        *off += (size_t)written;
        if (*off >= size) {
            *off = size - 1;
        }
    }
}

/**
 * @brief Serialize scan results as a JSON array.
 *
 * @param[in] aps   Array of access point records.
 * @param[in] count Number of valid entries in @p aps.
 * @return Heap-allocated JSON string, or NULL on allocation failure.
 *         The caller must free() the returned string.
 */
static char *build_scan_json(const wifi_ap_record_t *aps, uint16_t count)
{
    const size_t size = 32768;
    char *buf = malloc(size);
    if (buf == NULL) {
        return NULL;
    }

    size_t off = 0;
    appendf(buf, size, &off, "[");

    for (uint16_t i = 0; i < count; i++) {
        const wifi_ap_record_t *ap = &aps[i];

        char ssid[33];
        memcpy(ssid, ap->ssid, sizeof(ap->ssid) - 1);
        ssid[sizeof(ssid) - 1] = '\0';

        char ssid_esc[256];
        json_escape(ssid_esc, sizeof(ssid_esc), ssid);

        char phy[80];
        phy_modes_to_str(ap, phy, sizeof(phy));

        char country_raw[3] = { ap->country.cc[0], ap->country.cc[1], '\0' };
        char country_esc[16];
        json_escape(country_esc, sizeof(country_esc), country_raw);

        uint16_t ch_end = (ap->country.nchan > 0)
                              ? (uint16_t)(ap->country.schan + ap->country.nchan - 1)
                              : ap->country.schan;

        appendf(buf, size, &off,
                "%s{\"ssid\":\"%s\",\"bssid\":\"%02x:%02x:%02x:%02x:%02x:%02x\","
                "\"band\":\"%s\",\"freq\":%u,\"channel\":%u,\"second\":\"%s\","
                "\"bandwidth\":\"%s\",\"rssi\":%d,\"ant\":\"%s\","
                "\"auth\":\"%s\",\"pairwise\":\"%s\",\"group\":\"%s\","
                "\"phy\":\"%s\",\"wps\":%s,\"ftm_resp\":%s,\"ftm_init\":%s,"
                "\"dpp\":%s,\"country\":\"%s\",\"country_ch_start\":%u,"
                "\"country_ch_end\":%u,\"max_tx\":%d,"
                "\"he_bss_color\":%u,\"he_partial\":%s,\"he_disabled\":%s,"
                "\"he_bssid_index\":%u,\"vht1\":%u,\"vht2\":%u}",
                (i == 0) ? "" : ",",
                ssid_esc,
                ap->bssid[0], ap->bssid[1], ap->bssid[2],
                ap->bssid[3], ap->bssid[4], ap->bssid[5],
                channel_to_band(ap->primary),
                channel_to_freq_mhz(ap->primary),
                ap->primary,
                second_chan_to_str(ap->second),
                bandwidth_to_str(ap->bandwidth),
                ap->rssi,
                antenna_to_str(ap->ant),
                auth_mode_to_str(ap->authmode),
                cipher_to_str(ap->pairwise_cipher),
                cipher_to_str(ap->group_cipher),
                phy,
                ap->wps ? "true" : "false",
                ap->ftm_responder ? "true" : "false",
                ap->ftm_initiator ? "true" : "false",
                ap->akm_dpp ? "true" : "false",
                country_esc,
                ap->country.schan,
                ch_end,
                ap->country.max_tx_power,
                ap->he_ap.bss_color,
                ap->he_ap.partial_bss_color ? "true" : "false",
                ap->he_ap.bss_color_disabled ? "true" : "false",
                ap->he_ap.bssid_index,
                ap->vht_ch_freq1,
                ap->vht_ch_freq2);
    }

    appendf(buf, size, &off, "]");
    return buf;
}

/**
 * @brief Merge freshly scanned APs into the cache and expire stale entries.
 *
 * APs are matched by BSSID. Because a scan performed while the SoftAP is
 * serving a client can return only a subset of the nearby APs, results from
 * successive scans are accumulated instead of being replaced.
 *
 * @param[in] records AP records returned by the latest scan.
 * @param[in] count   Number of valid records.
 */
static void scan_cache_merge(const wifi_ap_record_t *records, uint16_t count)
{
    int64_t now_ms = esp_timer_get_time() / 1000;

    xSemaphoreTake(s_scan_cache_lock, portMAX_DELAY);

    for (uint16_t i = 0; i < count; i++) {
        const wifi_ap_record_t *ap = &records[i];
        int slot = -1;

        for (uint16_t j = 0; j < s_scan_cache_count; j++) {
            if (memcmp(s_scan_cache[j].bssid, ap->bssid, sizeof(ap->bssid)) == 0) {
                slot = j;
                break;
            }
        }

        if (slot < 0) {
            if (s_scan_cache_count < SCAN_CACHE_MAX) {
                slot = s_scan_cache_count++;
            } else {
                slot = 0;
                for (uint16_t j = 1; j < s_scan_cache_count; j++) {
                    if (s_scan_seen_ms[j] < s_scan_seen_ms[slot]) {
                        slot = j;
                    }
                }
            }
        }

        s_scan_cache[slot] = *ap;
        s_scan_seen_ms[slot] = now_ms;
    }

    for (uint16_t i = 0; i < s_scan_cache_count; ) {
        if (now_ms - s_scan_seen_ms[i] > SCAN_STALE_MS) {
            s_scan_cache[i] = s_scan_cache[s_scan_cache_count - 1];
            s_scan_seen_ms[i] = s_scan_seen_ms[s_scan_cache_count - 1];
            s_scan_cache_count--;
        } else {
            i++;
        }
    }

    xSemaphoreGive(s_scan_cache_lock);
}

/**
 * @brief Perform one scan and merge the result into the cache.
 *
 * @return ESP_OK on success, otherwise the scan error.
 */
static esp_err_t scan_and_merge(void)
{
    if (s_scan_engine_lock == NULL || s_scan_cache_lock == NULL) {
        return ESP_ERR_INVALID_STATE;
    }

    wifi_ap_record_t *records = malloc(sizeof(wifi_ap_record_t) * DEFAULT_SCAN_LIST_SIZE);
    if (records == NULL) {
        return ESP_ERR_NO_MEM;
    }

    wifi_scan_config_t scan_config = {
        .show_hidden = true,
        .scan_type = WIFI_SCAN_TYPE_ACTIVE,
        .scan_time.active.min = 0,
        .scan_time.active.max = 160,
        .home_chan_dwell_time = 30,
        .coex_background_scan = true,
    };

    xSemaphoreTake(s_scan_engine_lock, portMAX_DELAY);

    esp_err_t err = esp_wifi_scan_start(&scan_config, true);
    if (err == ESP_OK) {
        uint16_t found = 0;
        esp_wifi_scan_get_ap_num(&found);

        uint16_t number = DEFAULT_SCAN_LIST_SIZE;
        err = esp_wifi_scan_get_ap_records(&number, records);
        if (err == ESP_OK) {
            scan_cache_merge(records, number);
            ESP_LOGI(TAG, "Scan found %u APs, returned %u", found, number);
        }
    }

    xSemaphoreGive(s_scan_engine_lock);
    free(records);

    return err;
}

/**
 * @brief Serve the embedded captive-portal dashboard.
 *
 * @param[in] req HTTP request handle.
 * @return ESP_OK on success.
 */
static esp_err_t root_get_handler(httpd_req_t *req)
{
    httpd_resp_set_type(req, "text/html");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    return httpd_resp_send(req, (const char *)index_html_start,
                           (ssize_t)(index_html_end - index_html_start));
}

/**
 * @brief Perform a scan on demand and return the results as JSON.
 *
 * @param[in] req HTTP request handle.
 * @return ESP_OK on success.
 */
static esp_err_t scan_get_handler(httpd_req_t *req)
{
    if (s_scan_cache_lock == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                   "Scanner not ready");
    }

    scan_and_merge();

    xSemaphoreTake(s_scan_cache_lock, portMAX_DELAY);

    uint16_t count = s_scan_cache_count;
    wifi_ap_record_t *snapshot = NULL;
    if (count > 0) {
        snapshot = malloc(sizeof(*snapshot) * count);
        if (snapshot != NULL) {
            memcpy(snapshot, s_scan_cache, sizeof(*snapshot) * count);
        }
    }

    xSemaphoreGive(s_scan_cache_lock);

    if (count > 0 && snapshot == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                   "Out of memory");
    }

    char *json = build_scan_json(snapshot, count);
    free(snapshot);
    if (json == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                   "Could not build response");
    }

    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    esp_err_t res = httpd_resp_send(req, json, HTTPD_RESP_USE_STRLEN);
    free(json);

    return res;
}

/**
 * @brief Redirect any unknown request to the captive-portal dashboard.
 *
 * @param[in] req HTTP request handle.
 * @return ESP_OK on success.
 */
static esp_err_t captive_portal_handler(httpd_req_t *req)
{
    httpd_resp_set_status(req, "302 Found");
    httpd_resp_set_hdr(req, "Location", "http://" AP_IP_ADDR "/");
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_send(req, "Redirecting to the captive portal",
                           HTTPD_RESP_USE_STRLEN);
}

/**
 * @brief Start the HTTP server and register the portal handlers.
 */
static void start_http_server(void)
{
    httpd_config_t config = HTTPD_DEFAULT_CONFIG();
    config.stack_size = 8192;
    config.max_uri_handlers = 8;
    config.uri_match_fn = httpd_uri_match_wildcard;

    httpd_handle_t server = NULL;
    ESP_ERROR_CHECK(httpd_start(&server, &config));

    static const httpd_uri_t root_uri = {
        .uri = "/",
        .method = HTTP_GET,
        .handler = root_get_handler,
    };
    static const httpd_uri_t scan_uri = {
        .uri = "/api/scan",
        .method = HTTP_GET,
        .handler = scan_get_handler,
    };
    static const httpd_uri_t catch_all_uri = {
        .uri = "/*",
        .method = HTTP_GET,
        .handler = captive_portal_handler,
    };

    ESP_ERROR_CHECK(httpd_register_uri_handler(server, &root_uri));
    ESP_ERROR_CHECK(httpd_register_uri_handler(server, &scan_uri));
    ESP_ERROR_CHECK(httpd_register_uri_handler(server, &catch_all_uri));

    ESP_LOGI(TAG, "HTTP server started at http://%s/", AP_IP_ADDR);
}

/**
 * @brief Answer every DNS query with the SoftAP IPv4 address.
 *
 * This is what makes the dashboard behave like a captive portal: clients resolve
 * any hostname to 192.168.4.1, then the HTTP catch-all redirects them to the page.
 *
 * @param[in] pvParameters Unused task parameter.
 */
static void dns_server_task(void *pvParameters)
{
    (void)pvParameters;

    int sock = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
    if (sock < 0) {
        ESP_LOGE(TAG, "Unable to create DNS socket");
        vTaskDelete(NULL);
        return;
    }

    int reuse = 1;
    setsockopt(sock, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));

    struct sockaddr_in addr;
    memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_addr.s_addr = htonl(INADDR_ANY);
    addr.sin_port = htons(DNS_PORT);

    if (bind(sock, (struct sockaddr *)&addr, sizeof(addr)) != 0) {
        ESP_LOGE(TAG, "Unable to bind DNS socket");
        close(sock);
        vTaskDelete(NULL);
        return;
    }

    ESP_LOGI(TAG, "Captive-portal DNS server listening on port %d", DNS_PORT);

    uint8_t rx[512];
    uint8_t tx[600];

    while (true) {
        struct sockaddr_in from;
        socklen_t from_len = sizeof(from);
        int len = recvfrom(sock, rx, sizeof(rx), 0,
                           (struct sockaddr *)&from, &from_len);
        if (len < 12) {
            continue;
        }

        int p = 12;
        bool have_question = false;
        while (p < len) {
            uint8_t label = rx[p];
            if (label == 0) {
                p++;
                have_question = true;
                break;
            }
            if ((label & 0xC0) == 0xC0) {
                p += 2;
                have_question = true;
                break;
            }
            p += label + 1;
        }

        if (!have_question || p + 4 > len) {
            continue;
        }

        uint16_t qtype = (uint16_t)((rx[p] << 8) | rx[p + 1]);
        int q_end = p + 4;

        memcpy(tx, rx, (size_t)q_end);
        tx[2] = 0x81; /* QR=1, AA=1, RD=1 */
        tx[3] = 0x80; /* RA=1, RCODE=0 */
        tx[6] = 0x00;
        tx[7] = (qtype == 1) ? 0x01 : 0x00; /* ANCOUNT */
        tx[8] = 0x00;
        tx[9] = 0x00;
        tx[10] = 0x00;
        tx[11] = 0x00;

        int out = q_end;
        if (qtype == 1) {
            tx[out++] = 0xC0;
            tx[out++] = 0x0C; /* pointer to question name */
            tx[out++] = 0x00;
            tx[out++] = 0x01; /* TYPE A */
            tx[out++] = 0x00;
            tx[out++] = 0x01; /* CLASS IN */
            tx[out++] = 0x00;
            tx[out++] = 0x00;
            tx[out++] = 0x00;
            tx[out++] = 0x3C; /* TTL 60 s */
            tx[out++] = 0x00;
            tx[out++] = 0x04; /* RDLENGTH */
            tx[out++] = 192;
            tx[out++] = 168;
            tx[out++] = 4;
            tx[out++] = 1;
        }

        sendto(sock, tx, (size_t)out, 0, (struct sockaddr *)&from, from_len);
    }
}

/**
 * @brief Configure and start the SoftAP in AP+STA mode.
 *
 * AP+STA mode is used so the station side can still perform scans.
 */
static void wifi_init_softap(void)
{
    ESP_ERROR_CHECK(esp_netif_init());
    ESP_ERROR_CHECK(esp_event_loop_create_default());

    esp_netif_t *ap_netif = esp_netif_create_default_wifi_ap();
    assert(ap_netif);

    wifi_init_config_t cfg = WIFI_INIT_CONFIG_DEFAULT();
    ESP_ERROR_CHECK(esp_wifi_init(&cfg));

    wifi_config_t wifi_config;
    memset(&wifi_config, 0, sizeof(wifi_config));

    size_t ssid_len = strlen(AP_SSID);
    size_t pass_len = strlen(AP_PASSWORD);
    memcpy(wifi_config.ap.ssid, AP_SSID, ssid_len);
    wifi_config.ap.ssid_len = (uint8_t)ssid_len;
    wifi_config.ap.channel = AP_CHANNEL;
    wifi_config.ap.max_connection = AP_MAX_STA;

    if (pass_len >= 8) {
        memcpy(wifi_config.ap.password, AP_PASSWORD, pass_len);
        wifi_config.ap.authmode = WIFI_AUTH_WPA2_PSK;
    } else {
        wifi_config.ap.authmode = WIFI_AUTH_OPEN;
    }

    ESP_ERROR_CHECK(esp_wifi_set_mode(WIFI_MODE_APSTA));
    ESP_ERROR_CHECK(esp_wifi_set_config(WIFI_IF_AP, &wifi_config));
    ESP_ERROR_CHECK(esp_wifi_start());

    esp_netif_ip_info_t ip_info;
    if (esp_netif_get_ip_info(ap_netif, &ip_info) == ESP_OK) {
        ESP_LOGI(TAG, "SoftAP '%s' started, IP " IPSTR, AP_SSID, IP2STR(&ip_info.ip));
    }
}

/**
 * @brief Application entry point.
 *
 * Initializes NVS, starts the SoftAP, the captive-portal DNS server and the HTTP
 * dashboard.
 */
void app_main(void)
{
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }
    ESP_ERROR_CHECK(ret);

    wifi_init_softap();

    s_scan_cache_lock = xSemaphoreCreateMutex();
    s_scan_engine_lock = xSemaphoreCreateMutex();
    if (s_scan_cache_lock == NULL || s_scan_engine_lock == NULL) {
        ESP_LOGE(TAG, "Could not create scan locks");
        abort();
    }

    scan_and_merge();

    xTaskCreate(dns_server_task, "dns_server", 4096, NULL, 4, NULL);
    start_http_server();

#if CONFIG_SOC_WIFI_SUPPORT_5G
    ESP_LOGI(TAG, "This chip supports 2.4 GHz and 5 GHz scans.");
#else
    ESP_LOGI(TAG, "This chip is 2.4 GHz only; 5 GHz results appear on newer dual-band chips.");
#endif

    ESP_LOGI(TAG, "Join Wi-Fi '%s' (password '%s'), then open http://%s/",
             AP_SSID, AP_PASSWORD, AP_IP_ADDR);
}
